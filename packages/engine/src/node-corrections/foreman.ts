import { d2r, r2d } from "../astronomy/constants.js";
import type { AstroData } from "../astronomy/index.js";
import table from "./foreman.json" with { type: "json" };
import { withoutPerigee } from "./iho.js";
import type { Fundamentals, NodalCorrection } from "./types.js";

/** Changes in p, N and p′, phase in cycles, amplitude ratio, and latitude factor kind. */
type Satellite = [number, number, number, number, number, number];

/**
 * Foreman's nodal corrections, as t_tide and UTide evaluate them: each main line's satellites
 * summed, two of them scaled by the site's latitude, and shallow-water lines as products of
 * main lines. Lines t_tide gives neither keep f = 1 and u = 0. Generated by scripts/gen-foreman.py.
 */
export function foreman(latitude: number): Fundamentals {
  if (typeof latitude !== "number" || !(Math.abs(latitude) <= 90))
    throw new RangeError("invalidLatitude");
  // t_tide holds the latitude 5° from the equator, where the first factor grows without bound.
  // At exactly 0° t_tide divides by zero; this takes 5° north.
  const sinLat = Math.sin(d2r * (Math.abs(latitude) < 5 ? (latitude < 0 ? -5 : 5) : latitude));
  const latitudeFactor = [1, (0.36309 * (1 - 5 * sinLat * sinLat)) / sinLat, 2.59808 * sinLat];

  const main = (satellites: Satellite[]) => (a: AstroData) => {
    let re = 1;
    let im = 0;
    for (const [dp, dN, dpp, phase, ratio, kind] of satellites) {
      const angle = d2r * (dp * a.p.value + dN * a.N.value + dpp * a.pp.value + 360 * phase);
      const r = ratio * latitudeFactor[kind];
      re += r * Math.cos(angle);
      im += r * Math.sin(angle);
    }
    return { f: Math.hypot(re, im), u: r2d * Math.atan2(im, re) };
  };

  const fundamentals: Fundamentals = {};
  for (const [name, satellites] of Object.entries(table.satellites)) {
    const correction = main(satellites as Satellite[]);
    // Foreman's M1 (his NO1) argument holds one turn of p, as the catalog's does.
    fundamentals[name] =
      name === "M1" || name === "NO1"
        ? (a, turns = 1, epoch = a) => withoutPerigee(correction(a), epoch, turns - 1)
        : correction;
  }
  for (const [name, members] of Object.entries(table.products))
    fundamentals[name] = (a: AstroData): NodalCorrection =>
      (members as [string, number][]).reduce(
        ({ f, u }, [member, power]) => {
          const c = fundamentals[member](a);
          return { f: f * c.f ** Math.abs(power), u: u + power * c.u };
        },
        { f: 1, u: 0 },
      );
  return fundamentals;
}
